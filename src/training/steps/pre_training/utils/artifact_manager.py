    def _count_artifacts_by_type(self) -> Dict[str, int]:
        """Count artifacts by type."""
        counts = defaultdict(int)
        for metadata in self._artifact_registry.values():
            counts[metadata.artifact_type] += 1
        return dict(counts)

    def _count_artifacts_by_step(self) -> Dict[str, int]:
        """Count artifacts by step."""
        counts = defaultdict(int)
        for metadata in self._artifact_registry.values():
            counts[metadata.step_name] += 1
        return dict(counts)

    def _count_compressed_artifacts(self) -> int:
        """Count compressed artifacts."""
        count = 0
        for metadata in self._artifact_registry.values():
            if metadata.compression_used != CompressionType.NONE:
                count += 1
        return count


