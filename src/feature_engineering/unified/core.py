"""
Core interfaces and base classes for the unified feature generation system.

This module defines the fundamental interfaces that all feature generators
must implement, ensuring consistency and interoperability across the system.
"""

import asyncio
import logging
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Union, Callable, Tuple
from datetime import datetime
import pandas as pd
import numpy as np
