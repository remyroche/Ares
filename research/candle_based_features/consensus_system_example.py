def create_sample_data(n_samples: int = 2000) -> pd.DataFrame:
    """Create realistic sample OHLCV data for demonstration."""
    np.random.seed(42)
    
    # Generate price series with trend and volatility
    base_price = 100.0
    trend = np.linspace(0, 0.1, n_samples)  # 10% trend over period
    noise = np.random.normal(0, 0.02, n_samples)
    returns = trend + noise
    
    prices = base_price * np.exp(np.cumsum(returns))
    
    # Create OHLCV data
    data = pd.DataFrame({
        'open': prices * (1 + np.random.normal(0, 0.005, n_samples)),
        'high': prices * (1 + np.abs(np.random.normal(0, 0.01, n_samples))),
        'low': prices * (1 - np.abs(np.random.normal(0, 0.01, n_samples))),
        'close': prices,
        'volume': np.random.lognormal(10, 1, n_samples)
    }, index=pd.date_range('2020-01-01', periods=n_samples, freq='1min'))
    
    # Ensure OHLC constraints
    data['high'] = np.maximum(data['high'], np.maximum(data['open'], data['close']))
    data['low'] = np.minimum(data['low'], np.minimum(data['open'], data['close']))
    
    return data


