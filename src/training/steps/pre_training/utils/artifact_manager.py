# Register alias mappings to the same key sets
for alias, canonical in STEP_NAME_ALIASES.items():
    if canonical in _STEP_KEY_MAP:
        _STEP_KEY_MAP[alias] = _STEP_KEY_MAP[canonical]

_REVERSE_STEP_ALIASES: Dict[str, Set[str]] = defaultdict(set)
for alias, canonical in STEP_NAME_ALIASES.items():
    _REVERSE_STEP_ALIASES[canonical].add(alias)


def canonical_step_name(step_name: str) -> str:
    """Resolve a step name to its canonical representation."""
    if not step_name:
        return step_name
    return STEP_NAME_ALIASES.get(step_name, step_name)


def get_default_step_for_key(key: str) -> Optional[str]:
    """Infer the canonical step name that owns a given artifact key."""
    for step, keys in _STEP_KEY_MAP.items():
        if key in keys:
            return canonical_step_name(step)
    return None


def get_registered_keys_for_step(step_name: str) -> Set[str]:
    """Return the set of known artifact keys for a step (including aliases)."""
    canonical = canonical_step_name(step_name)
    keys = set(_STEP_KEY_MAP.get(canonical, frozenset()))
    for alias in _REVERSE_STEP_ALIASES.get(canonical, set()):
        keys.update(_STEP_KEY_MAP.get(alias, frozenset()))
    return keys


