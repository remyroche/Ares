    def get_model_performance_summary(self) -> Dict[str, Any]:
        """Get summary of model performance."""
        if not self.models:
            return {'error': 'No models available'}
        
        summary = {
            'total_models': len(self.models),
            'successful_models': len([m for m in self.models.values() if m['success']]),
            'model_performance': {},
            'best_model': None,
            'worst_model': None
        }
        
        # Calculate performance summary
        performance_scores = {}
        for model_name, model_result in self.models.items():
            if model_result['success']:
                performance = model_result['performance']
                f1_score = performance.get('f1_score', 0)
                performance_scores[model_name] = f1_score
                summary['model_performance'][model_name] = performance
        
        if performance_scores:
            best_model = max(performance_scores.items(), key=lambda x: x[1])
            worst_model = min(performance_scores.items(), key=lambda x: x[1])
            summary['best_model'] = best_model[0]
            summary['worst_model'] = worst_model[0]
        
        return summary
    
