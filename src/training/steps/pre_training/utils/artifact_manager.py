    def get_metrics(self) -> Dict[str, Any]:
        """Get comprehensive metrics about artifact manager performance."""
        if not self.config.enable_metrics:
            return {"metrics_disabled": True}

        total_operations = sum(self._operation_counts.values())
        total_errors = sum(self._error_counts.values())

        # Calculate success rate
        success_rate = (total_operations - total_errors) / total_operations if total_operations > 0 else 0.0

        # Get recent metrics (last 100 operations)
        recent_metrics = self._metrics[-100:] if self._metrics else []

        # Calculate average operation time
        avg_operation_time = sum(m.duration_seconds for m in recent_metrics) / len(recent_metrics) if recent_metrics else 0.0

        # Memory usage statistics
        memory_usage_mb = self._memory_usage_mb
        cache_usage_mb = sum(entry.memory_size_mb for entry in self._cache.values())

        return {
            "run_id": self._current_run_id,
            "total_operations": total_operations,
            "total_errors": total_errors,
            "success_rate": success_rate,
            "average_operation_time_seconds": avg_operation_time,
            "memory_usage_mb": memory_usage_mb,
            "cache_usage_mb": cache_usage_mb,
            "cache_entries": len(self._cache),
            "active_operations": len(self._active_operations),
            "artifacts_stored": len(self._artifact_registry),
            "compression_enabled": self.config.enable_compression,
            "caching_enabled": self.config.enable_caching,
            "thread_safety_enabled": self.config.enable_thread_safety,
            "recent_operations": len(recent_metrics)
        }

    def get_artifact_metadata(self, step_name: str, key: str) -> Optional[ArtifactMetadata]:
        """Get metadata for a specific artifact."""
        artifact_key = f"{canonical_step_name(step_name)}:{key}"
        return self._artifact_registry.get(artifact_key)

    def get_artifact_lineage(self, step_name: str, key: str) -> List[str]:
        """Get the lineage (parent artifacts) for a specific artifact."""
        metadata = self.get_artifact_metadata(step_name, key)
        return metadata.parent_artifacts if metadata else []

    def list_artifacts(self, step_name: Optional[str] = None, artifact_type: Optional[str] = None) -> List[ArtifactMetadata]:
        """List artifacts with optional filtering."""
        canonical = canonical_step_name(step_name) if step_name else None
        artifacts = []

        # Check memory artifacts first
        for metadata in self._artifact_registry.values():
            if canonical and canonical_step_name(metadata.step_name) != canonical:
                continue
            if artifact_type and metadata.artifact_type != artifact_type:
                continue
            artifacts.append(metadata)

        # Also check disk storage if step_name is specified
        if canonical:
            try:
                artifacts_dir = self.config.base_dir / canonical
                if artifacts_dir.exists():
                    # Load artifacts from disk to get metadata
                    disk_artifacts = self._load_artifacts_from_disk(canonical)
                    for key, artifact in disk_artifacts.items():
                        # Create metadata for disk artifacts
                        artifact_key = f"{canonical}:{key}"
                        if artifact_key not in self._artifact_registry:
                            metadata = ArtifactMetadata(
                                artifact_key=artifact_key,
                                step_name=canonical,
                                artifact_type=type(artifact.value).__name__ if artifact.value else 'unknown',
                                size_bytes=getattr(artifact, 'size_bytes', 0),
                                checksum=getattr(artifact, 'checksum', ''),
                                parent_artifacts=[],
                                tags={},
                                description=f"Artifact from disk storage"
                            )
                            if not artifact_type or metadata.artifact_type == artifact_type:
                                artifacts.append(metadata)
            except Exception as e:
                self._logger.warning(f"Failed to list disk artifacts: {e}")

        return sorted(artifacts, key=lambda x: x.created_at, reverse=True)

    def get_cache_stats(self) -> Dict[str, Any]:
        """Get cache performance statistics."""
        if not self.config.enable_caching:
            return {"caching_disabled": True}

        total_accesses = sum(entry.access_count for entry in self._cache.values())
        total_entries = len(self._cache)

        return {
            "cache_entries": total_entries,
            "memory_usage_mb": self._memory_usage_mb,
            "max_memory_mb": self.config.memory.cache_memory_mb,
            "total_accesses": total_accesses,
            "average_accesses_per_entry": total_accesses / total_entries if total_entries > 0 else 0,
            "lru_queue_length": len(self._cache_lru),
            "compression_enabled": self.config.enable_compression
        }

    def clear_cache(self) -> None:
        """Clear the artifact cache."""
        with self._lock:
            self._cache.clear()
            self._cache_lru.clear()
            self._memory_usage_mb = 0.0
            self._logger.info("Artifact cache cleared")

    def get_health_status(self) -> Dict[str, Any]:
        """Get health status of the artifact manager."""
        health = {
            "status": "healthy",
            "run_id": self._current_run_id,
            "active_operations": len(self._active_operations),
            "artifacts_count": len(self._artifact_registry),
            "cache_entries": len(self._cache),
            "memory_usage_mb": self._memory_usage_mb,
            "disk_usage_mb": self._get_disk_usage_mb(),
            "last_cleanup": self._last_cleanup.isoformat() if self._last_cleanup else None,
            "background_tasks_running": self.config.enable_health_checks
        }

        # Check for potential issues
        warnings = []

        if len(self._active_operations) > 10:
            warnings.append("High number of active operations")

        if self._memory_usage_mb > self.config.memory.max_memory_mb * 0.9:
            warnings.append("High memory usage")
            health["status"] = "warning"

        if len(self._error_counts) > 0:
            warnings.append(f"Recent errors: {dict(self._error_counts)}")
            if sum(self._error_counts.values()) > 10:
                health["status"] = "warning"

        health["warnings"] = warnings

        return health

    def _get_disk_usage_mb(self) -> float:
        """Get disk usage in MB for the current run directory."""
        try:
            if self._run_dir and self._run_dir.exists():
                total_size = sum(f.stat().st_size for f in self._run_dir.rglob('*') if f.is_file())
                return total_size / (1024 * 1024)
        except Exception as e:
            self._logger.warning(f"Failed to calculate disk usage: {e}")
        return 0.0

    def export_metrics(self, format: str = "json") -> str:
        """Export metrics in specified format."""
        metrics = self.get_metrics()
        cache_stats = self.get_cache_stats()
        health_status = self.get_health_status()

        export_data = {
            "timestamp": datetime.utcnow().isoformat(),
            "metrics": metrics,
            "cache_stats": cache_stats,
            "health_status": health_status,
            "configuration": asdict(self.config)
        }

        if format.lower() == "json":
            return json.dumps(export_data, indent=2, default=str)
        else:
            # Return as formatted string for other formats
            return str(export_data)

    def optimize_storage(self) -> Dict[str, Any]:
        """Perform storage optimization operations."""
        results = {
            "cache_cleanup": False,
            "old_runs_cleanup": False,
            "compression_reapplied": False,
            "memory_freed_mb": 0.0,
            "files_optimized": 0
        }

        with self._lock:
            # Force cache cleanup
            old_memory_usage = self._memory_usage_mb
            self._cleanup_cache()
            memory_freed = old_memory_usage - self._memory_usage_mb
            results["cache_cleanup"] = True
            results["memory_freed_mb"] = memory_freed

            # Force old runs cleanup
            self._cleanup_old_runs()
            results["old_runs_cleanup"] = True

            # Reapply compression to large artifacts if beneficial
            if self.config.enable_compression:
                optimized_count = self._reapply_compression()
                results["compression_reapplied"] = True
                results["files_optimized"] = optimized_count

        self._logger.info(f"Storage optimization completed: {results}")
        return results

