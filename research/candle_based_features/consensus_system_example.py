class ConsensusSystemDemo:
    """
    Comprehensive demonstration of the consensus-based ML indicator system.
    
    This demo shows how to:
    1. Train multiple ML models
    2. Compare their performance
    3. Generate consensus indicators
    4. Analyze interpretability
    5. Validate consensus quality
    """
    
    def __init__(self):
        self.consensus_system = None
        self.comparison_pipeline = None
        self.interpretability_analyzer = None
        self.results = {}
        
        logger.info("🎯 Consensus System Demo initialized")
    
    def run_complete_demo(self, data: pd.DataFrame, symbol: str = 'BTCUSDT') -> Dict[str, Any]:
        """
        Run the complete consensus system demonstration.
        
        Args:
            data: Historical OHLCV data
            symbol: Trading symbol
            
        Returns:
            Complete demonstration results
        """
        logger.info(f"🚀 Starting complete consensus system demo for {symbol}")
        start_time = time.time()
        
        demo_results = {
            'symbol': symbol,
            'start_time': start_time,
            'data_samples': len(data),
            'steps_completed': [],
            'results': {}
        }
        
        try:
            # Step 1: Train consensus system
            logger.info("📚 Step 1: Training consensus system...")
            consensus_results = self._train_consensus_system(data, symbol)
            demo_results['steps_completed'].append('consensus_training')
            demo_results['results']['consensus_training'] = consensus_results
            
            # Step 2: Model comparison analysis
            logger.info("🔍 Step 2: Model comparison analysis...")
            comparison_results = self._analyze_model_comparison()
            demo_results['steps_completed'].append('model_comparison')
            demo_results['results']['model_comparison'] = comparison_results
            
            # Step 3: Interpretability analysis
            logger.info("🧠 Step 3: Interpretability analysis...")
            interpretability_results = self._analyze_interpretability()
            demo_results['steps_completed'].append('interpretability_analysis')
            demo_results['results']['interpretability_analysis'] = interpretability_results
            
            # Step 4: Consensus validation
            logger.info("✅ Step 4: Consensus validation...")
            validation_results = self._validate_consensus_quality()
            demo_results['steps_completed'].append('consensus_validation')
            demo_results['results']['consensus_validation'] = validation_results
            
            # Step 5: Real-time generation demo
            logger.info("⚡ Step 5: Real-time generation demo...")
            realtime_results = self._demo_realtime_generation(data)
            demo_results['steps_completed'].append('realtime_generation')
            demo_results['results']['realtime_generation'] = realtime_results
            
            # Step 6: Performance evaluation
            logger.info("📊 Step 6: Performance evaluation...")
            performance_results = self._evaluate_system_performance(data)
            demo_results['steps_completed'].append('performance_evaluation')
            demo_results['results']['performance_evaluation'] = performance_results
            
            demo_results['success'] = True
            
        except Exception as e:
            logger.error(f"Demo failed: {e}")
            demo_results['success'] = False
            demo_results['error'] = str(e)
        
        demo_results['end_time'] = time.time()
        demo_results['total_time'] = demo_results['end_time'] - start_time
        
        logger.info(f"🎉 Complete demo finished in {demo_results['total_time']:.2f} seconds")
        return demo_results
    
    def _train_consensus_system(self, data: pd.DataFrame, symbol: str) -> Dict[str, Any]:
        """Train the consensus system with multiple models."""
        # Configure consensus system
        config = ConsensusSystemConfig(
            min_models_required=2,
            min_agreement_threshold=0.6,
            min_confidence_threshold=0.7,
            consensus_method=ConsensusMethod.CONFIDENCE_WEIGHTED,
            enable_quality_control=True,
            enable_consensus_interpretability=True
        )
        
        # Create consensus system
        self.consensus_system = create_consensus_system(config)
        
        # Train system
        training_results = self.consensus_system.train_consensus_system(
            data, 
            symbol=symbol,
            model_types=[ModelType.LIGHTGBM, ModelType.RANDOM_FOREST]
        )
        
        return training_results
    
    def _analyze_model_comparison(self) -> Dict[str, Any]:
        """Analyze model comparison results."""
        if not self.consensus_system:
            return {'error': 'Consensus system not trained'}
        
        comparison_pipeline = self.consensus_system.comparison_pipeline
        comparison_results = comparison_pipeline.comparison_history[-1] if comparison_pipeline.comparison_history else {}
        
        # Extract key metrics
        analysis = {
            'total_models': len(comparison_results.get('model_results', {})),
            'successful_models': len([r for r in comparison_results.get('model_results', {}).values() if r.get('success', False)]),
            'model_performance': {},
            'consensus_analysis': comparison_results.get('consensus_analysis', {}),
            'performance_comparison': comparison_results.get('performance_comparison', {})
        }
        
        # Analyze individual model performance
        for model_name, result in comparison_results.get('model_results', {}).items():
            if result.get('success', False):
                performance = result.get('performance', {})
                analysis['model_performance'][model_name] = {
                    'f1_score': performance.get('f1_score', 0),
                    'accuracy': performance.get('accuracy', 0),
                    'confidence': result.get('confidence', 0)
                }
        
        return analysis
    
    def _analyze_interpretability(self) -> Dict[str, Any]:
        """Analyze interpretability across models."""
        if not self.consensus_system or not self.consensus_system.interpretability_analyzer:
            return {'error': 'Interpretability analyzer not available'}
        
        # Get interpretability results from consensus system
        interpretability_results = self.consensus_system.consensus_history[-1].get('interpretability_results', {})
        
        analysis = {
            'consensus_features': interpretability_results.get('consensus_features', {}),
            'feature_agreement': interpretability_results.get('feature_agreement', {}),
            'model_consensus_scores': interpretability_results.get('model_consensus_scores', {}),
            'top_consensus_features': interpretability_results.get('top_consensus_features', [])
        }
        
        return analysis
    
    def _validate_consensus_quality(self) -> Dict[str, Any]:
        """Validate the quality of consensus indicators."""
        if not self.consensus_system:
            return {'error': 'Consensus system not trained'}
        
        # Get quality validation from training results
        training_results = self.consensus_system.consensus_history[-1]
        quality_validation = training_results.get('quality_validation', {})
        
        validation_analysis = {
            'consensus_strength': quality_validation.get('consensus_strength', 0),
            'model_agreement': quality_validation.get('model_agreement', 0),
            'indicator_stability': quality_validation.get('indicator_stability', 0),
            'quality_score': quality_validation.get('quality_score', 0),
            'validation_passed': quality_validation.get('validation_passed', False)
        }
        
        return validation_analysis
    
    def _demo_realtime_generation(self, data: pd.DataFrame) -> Dict[str, Any]:
        """Demonstrate real-time consensus indicator generation."""
        if not self.consensus_system:
            return {'error': 'Consensus system not trained'}
        
        # Use last portion of data as "new" data
        new_data = data.iloc[-100:]
        
        # Generate consensus indicators
        consensus_indicators = self.consensus_system.generate_consensus_indicators(new_data)
        
        if 'error' in consensus_indicators:
            return consensus_indicators
        
        # Analyze real-time results
        realtime_analysis = {
            'indicators_generated': len(consensus_indicators['consensus_indicators']),
            'models_used': len(consensus_indicators['models_used']),
            'consensus_method': consensus_indicators['consensus_method'],
            'reliability_distribution': consensus_indicators['reliability_levels'].value_counts().to_dict(),
            'indicator_statistics': {
                'mean': consensus_indicators['consensus_indicators'].mean(),
                'std': consensus_indicators['consensus_indicators'].std(),
                'min': consensus_indicators['consensus_indicators'].min(),
                'max': consensus_indicators['consensus_indicators'].max()
            }
        }
        
        return realtime_analysis
    
    def _evaluate_system_performance(self, data: pd.DataFrame) -> Dict[str, Any]:
        """Evaluate overall system performance."""
        if not self.consensus_system:
            return {'error': 'Consensus system not trained'}
        
