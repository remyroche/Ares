class PreTrainingArtifactManager:
    """
    Enhanced centralized artifact storage with optional disk spilling.

    Features:
    - Robust error handling with retry mechanisms
    - Compression support for storage optimization
    - Comprehensive metadata tracking and artifact lineage
    - Thread safety and concurrent access protection
    - Performance monitoring and metrics collection
    - Intelligent caching strategies with memory management
    """

    def __init__(self, config: Optional[ArtifactConfig] = None) -> None:
        self.config = config or ArtifactConfig()

        # Core storage
        self._artifacts: Dict[str, Dict[str, StoredArtifact]] = {}
        self._metadata: Dict[str, Dict[str, Any]] = {}
        self._artifact_registry: Dict[str, ArtifactMetadata] = {}
        self._current_run_id: Optional[str] = None
        self._run_dir: Optional[Path] = None

        # Thread safety
        self._lock = threading.RLock() if self.config.enable_thread_safety else None
        self._active_operations: Set[str] = set()

        # Caching system
        self._cache: Dict[str, CacheEntry] = {}
        self._cache_lru: deque = deque()

        # Performance monitoring
        self._metrics: List[OperationMetrics] = []
        self._operation_counts: Dict[OperationType, int] = defaultdict(int)
        self._error_counts: Dict[str, int] = defaultdict(int)

        # Memory management
        self._memory_usage_mb = 0.0
        self._last_cleanup = datetime.utcnow()

        # Compression utilities
        self._compressor = self.ArtifactCompressor()

        # Logger
        self._logger = logging.getLogger(__name__).getChild("PreTrainingArtifactManager")

        # Initialize directories
        self.config.base_dir.mkdir(parents=True, exist_ok=True)

        # Start background tasks
        self._start_background_tasks()

        self.reset_run()

    # ------------------------------------------------------------------
    # Helper Classes and Methods
    # ------------------------------------------------------------------

    class ArtifactCompressor:
        """Utility class for artifact compression."""

        def __init__(self):
            self._logger = logging.getLogger(__name__ + ".ArtifactCompressor")

        def should_compress(self, data_size_bytes: int, config: CompressionConfig) -> bool:
            """Determine if data should be compressed based on configuration."""
            if not config.enabled:
                return False

            min_size_bytes = int(config.min_size_mb * 1024 * 1024)
            return data_size_bytes >= min_size_bytes

        def choose_compression(self, data_size_bytes: int, config: CompressionConfig) -> CompressionType:
            """Choose the best compression algorithm for the data."""
            if not config.enabled:
                return CompressionType.NONE

            if config.algorithm != CompressionType.AUTO:
                return config.algorithm

            # Auto-select based on data size and characteristics
            if data_size_bytes > 100 * 1024 * 1024:  # > 100MB
                return CompressionType.LZ4  # Fast compression for large data
            else:
                return CompressionType.GZIP  # Better compression ratio for smaller data

        def compress_data(self, data: Any, compression_type: CompressionType) -> bytes:
            """Compress data using the specified algorithm."""
            try:
                if compression_type == CompressionType.GZIP:
                    return gzip.compress(pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL))
                elif compression_type == CompressionType.LZ4:
                    return lz4.frame.compress(pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL))
                else:
                    return pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL)
            except Exception as e:
                self._logger.warning(f"Compression failed, falling back to no compression: {e}")
                return pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL)

        def decompress_data(self, compressed_data: bytes, compression_type: CompressionType) -> Any:
            """Decompress data using the specified algorithm."""
            try:
                if compression_type == CompressionType.GZIP:
                    return pickle.loads(gzip.decompress(compressed_data))
                elif compression_type == CompressionType.LZ4:
                    return pickle.loads(lz4.frame.decompress(compressed_data))
                else:
                    return pickle.loads(compressed_data)
            except Exception as e:
                self._logger.error(f"Decompression failed: {e}")
                raise

    def _start_background_tasks(self) -> None:
        """Start background maintenance tasks."""
        if self.config.enable_health_checks:
            # Start cleanup task
            cleanup_task = threading.Thread(
                target=self._background_cleanup,
                daemon=True,
                name="ArtifactManagerCleanup"
            )
            cleanup_task.start()

            self._logger.debug("Background cleanup task started")

    def _background_cleanup(self) -> None:
        """Background task for periodic cleanup and maintenance."""
        while True:
            try:
                time.sleep(self.config.cleanup_interval_seconds)
                self._perform_cleanup()
            except Exception as e:
                self._logger.error(f"Background cleanup failed: {e}")

    def _perform_cleanup(self) -> None:
        """Perform cleanup operations."""
        with self._lock:
            current_time = datetime.utcnow()

            # Check if cleanup is needed
            if (current_time - self._last_cleanup).total_seconds() < self.config.cleanup_interval_seconds:
                return

            # Clean up old cache entries
            self._cleanup_cache()

            # Clean up old run directories
            self._cleanup_old_runs()

            # Force garbage collection if enabled
            if self.config.memory.enable_gc_collection:
                import gc
                gc.collect()

            self._last_cleanup = current_time

    def _cleanup_cache(self) -> None:
        """Clean up old cache entries based on LRU and memory usage."""
        if not self.config.enable_caching:
            return

        max_memory_mb = self.config.memory.cache_memory_mb
        current_memory_mb = self._memory_usage_mb

        # Remove LRU entries if memory usage is high
        while current_memory_mb > max_memory_mb and self._cache_lru:
            oldest_key = self._cache_lru.popleft()
            if oldest_key in self._cache:
                entry = self._cache.pop(oldest_key)
                current_memory_mb -= entry.memory_size_mb
                self._logger.debug(f"Evicted cache entry: {oldest_key}")

        # Remove entries not accessed recently (older than 1 hour)
        cutoff_time = datetime.utcnow() - timedelta(hours=1)
        to_remove = []

        for key, entry in self._cache.items():
            if entry.last_accessed < cutoff_time and entry.access_count < 2:
                to_remove.append(key)
                current_memory_mb -= entry.memory_size_mb

        for key in to_remove:
            self._cache.pop(key, None)

        self._memory_usage_mb = current_memory_mb

    def _calculate_memory_usage(self, data: Any) -> float:
        """Calculate memory usage of data in MB."""
        try:
            if isinstance(data, pd.DataFrame):
                return data.memory_usage(deep=True).sum() / (1024 * 1024)
            elif isinstance(data, pd.Series):
                return data.memory_usage(deep=True) / (1024 * 1024)
            elif isinstance(data, np.ndarray):
                return data.nbytes / (1024 * 1024)
            else:
                # Estimate for other objects
                return len(pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL)) / (1024 * 1024)
        except Exception:
            return 0.0

    def _generate_checksum(self, data: Any) -> str:
        """Generate checksum for data integrity."""
        try:
            data_bytes = pickle.dumps(data, protocol=pickle.HIGHEST_PROTOCOL)
            return hashlib.md5(data_bytes).hexdigest()
        except Exception:
            return hashlib.md5(str(data).encode()).hexdigest()

    def _record_metrics(self, metrics: OperationMetrics) -> None:
        """Record operation metrics."""
        if not self.config.enable_metrics:
            return

        self._metrics.append(metrics)
        self._operation_counts[metrics.operation_type] += 1

        # Keep only recent metrics (last 1000 operations)
        if len(self._metrics) > 1000:
            self._metrics = self._metrics[-1000:]

    def _retry_operation(self, operation_func, *args, **kwargs) -> Any:
        """Execute operation with retry logic."""
        last_exception = None

        for attempt in range(self.config.retry.max_retries + 1):
            try:
                return operation_func(*args, **kwargs)
            except self.config.retry.retryable_exceptions as e:
                last_exception = e
                if attempt < self.config.retry.max_retries:
                    delay = self._calculate_retry_delay(attempt)
                    self._logger.warning(f"Operation failed (attempt {attempt + 1}), retrying in {delay}s: {e}")
                    time.sleep(delay)
                else:
                    self._logger.error(f"Operation failed after {self.config.retry.max_retries + 1} attempts: {e}")
                    raise
            except Exception as e:
                # Non-retryable exception
                self._logger.error(f"Non-retryable operation failure: {e}")
                raise

        if last_exception:
            raise last_exception

    def _calculate_retry_delay(self, attempt: int) -> float:
        """Calculate delay for retry attempts."""
        if self.config.retry.strategy == RetryStrategy.EXPONENTIAL_BACKOFF:
            delay = self.config.retry.base_delay * (2 ** attempt)
        elif self.config.retry.strategy == RetryStrategy.LINEAR_BACKOFF:
            delay = self.config.retry.base_delay * (attempt + 1)
        else:  # FIXED_DELAY
            delay = self.config.retry.base_delay

        return min(delay, self.config.retry.max_delay)

    def _safe_operation(self, operation_type: OperationType, operation_func, *args, **kwargs) -> Any:
        """Execute operation with thread safety and metrics."""
        operation_id = f"{operation_type.value}_{uuid.uuid4().hex[:8]}"

        with self._lock:
            self._active_operations.add(operation_id)

        try:
            start_time = time.time()
            result = self._retry_operation(operation_func, *args, **kwargs)
            duration = time.time() - start_time

            # Record success metrics
            metrics = OperationMetrics(
                operation_type=operation_type,
                artifact_key=kwargs.get('artifact_key', 'unknown'),
                step_name=kwargs.get('step_name', 'unknown'),
                duration_seconds=duration,
                success=True,
                bytes_processed=kwargs.get('bytes_processed', 0)
            )
            self._record_metrics(metrics)

            return result

        except Exception as e:
            duration = time.time() - start_time

            # Record failure metrics
            metrics = OperationMetrics(
                operation_type=operation_type,
                artifact_key=kwargs.get('artifact_key', 'unknown'),
                step_name=kwargs.get('step_name', 'unknown'),
                duration_seconds=duration,
                success=False,
                error_message=str(e)
            )
            self._record_metrics(metrics)

            raise
        finally:
            with self._lock:
                self._active_operations.discard(operation_id)

    def _update_cache_entry(self, artifact_key: str, data: Any, metadata: ArtifactMetadata) -> None:
        """Update or create cache entry."""
        if not self.config.enable_caching:
            return

        memory_size = self._calculate_memory_usage(data)

        # Check if we need to evict entries due to memory pressure
        if self._memory_usage_mb + memory_size > self.config.memory.cache_memory_mb:
            self._cleanup_cache()

            # If still over limit, don't cache
            if self._memory_usage_mb + memory_size > self.config.memory.cache_memory_mb:
                self._logger.debug(f"Skipping cache for {artifact_key} due to memory pressure")
                return

        # Create or update cache entry
        if artifact_key in self._cache:
            # Update existing entry
            entry = self._cache[artifact_key]
            old_size = entry.memory_size_mb
            self._memory_usage_mb = self._memory_usage_mb - old_size + memory_size
        else:
            # Create new entry
            self._memory_usage_mb += memory_size
            self._cache_lru.append(artifact_key)

        # Create cache entry
        cache_entry = CacheEntry(
            artifact_key=artifact_key,
            data=data,
            metadata=metadata,
            memory_size_mb=memory_size
        )

        self._cache[artifact_key] = cache_entry

    # ------------------------------------------------------------------
    # Lifecycle
    # ------------------------------------------------------------------
    def reset_run(self) -> None:
        """Clear all artifacts and prepare storage for a new pipeline run."""
        with self._lock:
            # Clear all storage
            self._artifacts.clear()
            self._metadata.clear()
            self._artifact_registry.clear()

            # Reset cache and memory tracking
            self._cache.clear()
            self._cache_lru.clear()
            self._memory_usage_mb = 0.0

            # Reset metrics
            self._metrics.clear()
            self._operation_counts.clear()
            self._error_counts.clear()

            # Create new run directory
            self._current_run_id = datetime.utcnow().strftime("%Y%m%d_%H%M%S") + f"_{uuid.uuid4().hex[:8]}"
            self._run_dir = self.config.base_dir / self._current_run_id

            # Clean up old run directory if it exists
            if self._run_dir.exists():
                try:
                    shutil.rmtree(self._run_dir, ignore_errors=True)
                except Exception as e:
                    self._logger.warning(f"Failed to remove old run directory: {e}")

            # Create new run directory
            self._run_dir.mkdir(parents=True, exist_ok=True)

            # Clean up old runs
            self._cleanup_old_runs()

            self._logger.debug(f"Initialized enhanced artifact storage for run {self._current_run_id}")

    def get_run_id(self) -> Optional[str]:
        """Get the current run ID."""
        return self._current_run_id

    def get_run_dir(self) -> Optional[Path]:
        """Get the current run directory."""
        return self._run_dir

    def _cleanup_old_runs(self) -> None:
        """Remove old run directories beyond the retention limit."""
        try:
            run_dirs = sorted(
                [p for p in self.config.base_dir.iterdir() if p.is_dir()],
                key=lambda p: p.stat().st_mtime,
                reverse=True,
            )
            for old_run in run_dirs[self.config.max_runs_to_keep :]:
                shutil.rmtree(old_run, ignore_errors=True)
        except Exception as exc:  # pragma: no cover - best effort cleanup
            self._logger.debug("Failed to cleanup old artifact runs: %s", exc, exc_info=True)

