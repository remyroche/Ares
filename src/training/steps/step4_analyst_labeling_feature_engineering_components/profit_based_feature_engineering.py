"""
Profit-Based Feature Engineering for Triple Barrier Method.

This module creates comprehensive profit-based features from the potential_profit_pct
column generated by the triple barrier method. All features are created using
vectorized operations for optimal performance.
"""

import pandas as pd
import numpy as np
from typing import Dict, List, Optional, Tuple
from dataclasses import dataclass
import logging

from src.utils.logging import get_logger
from src.utils.decorators import handle_errors, with_tracing_span


@dataclass
class ProfitFeatureConfig:
    """Configuration for profit-based feature engineering."""
    
    # Basic profit features
    include_basic_features: bool = True
    
    # Interaction features
    include_interaction_features: bool = True
    interaction_indicators: List[str] = None  # Will be auto-detected if None
    
    # Risk-reward features
    include_risk_reward_features: bool = True
    volatility_windows: List[int] = None  # Will default to [5, 10, 20, 50]
    
    # Momentum features
    include_momentum_features: bool = True
    momentum_windows: List[int] = None  # Will default to [1, 3, 5]
    trend_windows: List[int] = None  # Will default to [5, 10, 20]
    
    # Volatility features
    include_volatility_features: bool = True
    volatility_windows: List[int] = None  # Will default to [5, 10, 20, 50]
    
    # Rolling statistical features
    include_rolling_features: bool = True
    rolling_windows: List[int] = None  # Will default to [5, 10, 20, 50]
    
    # Categorical features
    include_categorical_features: bool = True
    profit_bins: List[float] = None  # Will default to [-0.05, -0.02, -0.01, 0, 0.01, 0.02, 0.05]
    extreme_profit_threshold: float = 0.03
    extreme_loss_threshold: float = -0.02


class ProfitBasedFeatureEngineer:
    """
    Vectorized profit-based feature engineering for triple barrier method.
    
    Creates comprehensive features from potential_profit_pct column using
    vectorized operations for optimal performance.
    """
    
    def __init__(self, config: Optional[ProfitFeatureConfig] = None):
        """Initialize the profit-based feature engineer."""
        self.config = config or ProfitFeatureConfig()
        self.logger = get_logger("ProfitBasedFeatureEngineer")
        
        # Set default values for lists
        if self.config.interaction_indicators is None:
            self.config.interaction_indicators = [
                'rsi', 'macd', 'bb_upper', 'bb_lower', 'bb_middle',
                'ema_12', 'ema_26', 'sma_20', 'sma_50', 'sma_200',
                'atr', 'adx', 'cci', 'stoch_k', 'stoch_d'
            ]
        
        if self.config.volatility_windows is None:
            self.config.volatility_windows = [5, 10, 20, 50]
            
        if self.config.momentum_windows is None:
            self.config.momentum_windows = [1, 3, 5]
            
        if self.config.trend_windows is None:
            self.config.trend_windows = [5, 10, 20]
            
        if self.config.rolling_windows is None:
            self.config.rolling_windows = [5, 10, 20, 50]
            
        if self.config.profit_bins is None:
            self.config.profit_bins = [-0.05, -0.02, -0.01, 0, 0.01, 0.02, 0.05]
    
    @handle_errors(
        exceptions=(Exception,),
        default_return=pd.DataFrame(),
        context="profit_feature_engineering.create_all_features"
    )
    @with_tracing_span("ProfitFeatureEngineering.create_all_features", log_args=False)
    def create_all_profit_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """
        Create all configured profit-based features using vectorized operations.
        
        Args:
            data: DataFrame with 'potential_profit_pct' column
            
        Returns:
            DataFrame with original data plus profit-based features
        """
        if 'potential_profit_pct' not in data.columns:
            self.logger.warning("No 'potential_profit_pct' column found. Skipping profit feature engineering.")
            return data
        
        self.logger.info(f"Creating profit-based features for {len(data)} samples")
        
        # Create a copy to avoid modifying original data
        result = data.copy()
        
        # Create features in order of complexity
        if self.config.include_basic_features:
            result = self._create_basic_profit_features(result)
            
        if self.config.include_categorical_features:
            result = self._create_profit_categorical_features(result)
            
        if self.config.include_interaction_features:
            result = self._create_profit_interaction_features(result)
            
        if self.config.include_risk_reward_features:
            result = self._create_risk_reward_features(result)
            
        if self.config.include_momentum_features:
            result = self._create_profit_momentum_features(result)
            
        if self.config.include_volatility_features:
            result = self._create_profit_volatility_features(result)
            
        if self.config.include_rolling_features:
            result = self._create_rolling_profit_features(result)
        
        # Log feature creation summary
        original_cols = len(data.columns)
        new_cols = len(result.columns) - original_cols
        self.logger.info(f"Created {new_cols} new profit-based features")
        self.logger.info(f"Total features: {len(result.columns)}")
        
        return result
    
    def _create_basic_profit_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create basic profit features using vectorized operations."""
        profit = data['potential_profit_pct']
        
        # Basic transformations
        data['profit_abs'] = np.abs(profit)
        data['profit_log_abs'] = np.log1p(np.abs(profit))  # log1p handles zeros
        data['profit_sign'] = np.sign(profit)
        data['profit_positive'] = (profit > 0).astype(int)
        data['profit_negative'] = (profit < 0).astype(int)
        data['profit_squared'] = profit ** 2
        data['profit_cubed'] = profit ** 3
        
        return data
    
    def _create_profit_categorical_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create categorical profit features using vectorized operations."""
        profit = data['potential_profit_pct']
        
        # Create profit categories using pd.cut
        labels = ['extreme_loss', 'high_loss', 'medium_loss', 'small_loss', 
                 'small_profit', 'medium_profit', 'high_profit', 'extreme_profit']
        
        data['profit_category'] = pd.cut(
            profit, 
            bins=self.config.profit_bins, 
            labels=labels[:len(self.config.profit_bins)-1],
            include_lowest=True
        )
        
        # One-hot encode categories
        category_dummies = pd.get_dummies(data['profit_category'], prefix='profit_cat')
        data = pd.concat([data, category_dummies], axis=1)
        
        # Extreme profit/loss flags
        data['extreme_profit'] = (profit > self.config.extreme_profit_threshold).astype(int)
        data['extreme_loss'] = (profit < self.config.extreme_loss_threshold).astype(int)
        
        # Remove the original categorical column
        data = data.drop('profit_category', axis=1)
        
        return data
    
    def _create_profit_interaction_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create interaction features between profit and technical indicators."""
        profit = data['potential_profit_pct']
        
        for indicator in self.config.interaction_indicators:
            if indicator in data.columns:
                # Linear interaction
                data[f'{indicator}_profit_interaction'] = data[indicator] * profit
                
                # Quadratic interaction
                data[f'{indicator}_profit_squared_interaction'] = data[indicator] * (profit ** 2)
                
                # Conditional interactions
                data[f'{indicator}_positive_profit_interaction'] = data[indicator] * profit * (profit > 0)
                data[f'{indicator}_negative_profit_interaction'] = data[indicator] * profit * (profit < 0)
        
        return data
    
    def _create_risk_reward_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create risk-reward features using vectorized operations."""
        profit = data['potential_profit_pct']
        
        # Basic risk-reward ratio (using absolute values)
        data['risk_reward_ratio'] = np.abs(profit) / (np.abs(profit) + 0.001)  # Avoid division by zero
        
        # Volatility-adjusted features for different windows
        for window in self.config.volatility_windows:
            if len(data) >= window:
                # Rolling volatility of profit
                profit_vol = profit.rolling(window=window, min_periods=1).std()
                
                # Volatility-adjusted profit
                data[f'vol_adj_profit_{window}'] = profit / (profit_vol + 0.001)
                
                # Risk-reward with volatility
                data[f'risk_reward_vol_{window}'] = np.abs(profit) / (profit_vol + 0.001)
                
                # Sharpe-like ratio
                profit_mean = profit.rolling(window=window, min_periods=1).mean()
                data[f'sharpe_like_{window}'] = (profit - profit_mean) / (profit_vol + 0.001)
        
        # Kelly criterion inspired feature
        win_rate = (profit > 0).rolling(window=20, min_periods=1).mean()
        avg_win = profit.rolling(window=20, min_periods=1).apply(
            lambda x: x[x > 0].mean() if len(x[x > 0]) > 0 else 0
        )
        avg_loss = profit.rolling(window=20, min_periods=1).apply(
            lambda x: abs(x[x < 0].mean()) if len(x[x < 0]) > 0 else 0.001
        )
        
        data['kelly_fraction'] = (win_rate * avg_win - (1 - win_rate) * avg_loss) / (avg_win + 0.001)
        data['kelly_fraction'] = np.clip(data['kelly_fraction'], 0, 1)  # Clip to [0, 1]
        
        return data
    
    def _create_profit_momentum_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create momentum features for profit potential."""
        profit = data['potential_profit_pct']
        
        # Momentum (change in profit potential)
        for window in self.config.momentum_windows:
            if len(data) >= window:
                data[f'profit_momentum_{window}'] = profit.diff(window)
        
        # Acceleration (change in momentum)
        if len(data) >= 2:
            data['profit_acceleration'] = data['profit_momentum_1'].diff()
        
        # Trend features (rolling mean)
        for window in self.config.trend_windows:
            if len(data) >= window:
                data[f'profit_trend_{window}'] = profit.rolling(window=window, min_periods=1).mean()
        
        # RSI on profit (simplified version)
        if len(data) >= 14:
            profit_gains = profit.where(profit > 0, 0)
            profit_losses = -profit.where(profit < 0, 0)
            
            avg_gains = profit_gains.rolling(window=14, min_periods=1).mean()
            avg_losses = profit_losses.rolling(window=14, min_periods=1).mean()
            
            rs = avg_gains / (avg_losses + 0.001)
            data['profit_rsi'] = 100 - (100 / (1 + rs))
        
        # MACD on profit (simplified version)
        if len(data) >= 26:
            ema_12 = profit.ewm(span=12).mean()
            ema_26 = profit.ewm(span=26).mean()
            data['profit_macd'] = ema_12 - ema_26
            data['profit_macd_signal'] = data['profit_macd'].ewm(span=9).mean()
            data['profit_macd_histogram'] = data['profit_macd'] - data['profit_macd_signal']
        
        return data
    
    def _create_profit_volatility_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create volatility features for profit potential."""
        profit = data['potential_profit_pct']
        
        # Rolling volatility for different windows
        for window in self.config.volatility_windows:
            if len(data) >= window:
                data[f'profit_volatility_{window}'] = profit.rolling(window=window, min_periods=1).std()
        
        # Volatility ratios
        if len(data) >= 20:
            vol_5 = data['profit_volatility_5']
            vol_20 = data['profit_volatility_20']
            data['profit_vol_ratio_5_20'] = vol_5 / (vol_20 + 0.001)
        
        # Volatility percentiles
        if len(data) >= 50:
            data['profit_vol_percentile'] = profit.rolling(window=50, min_periods=1).apply(
                lambda x: pd.Series(x).rank(pct=True).iloc[-1]
            )
        
        return data
    
    def _create_rolling_profit_features(self, data: pd.DataFrame) -> pd.DataFrame:
        """Create rolling statistical features for profit potential."""
        profit = data['potential_profit_pct']
        
        for window in self.config.rolling_windows:
            if len(data) >= window:
                # Basic statistics
                data[f'profit_mean_{window}'] = profit.rolling(window=window, min_periods=1).mean()
                data[f'profit_std_{window}'] = profit.rolling(window=window, min_periods=1).std()
                data[f'profit_min_{window}'] = profit.rolling(window=window, min_periods=1).min()
                data[f'profit_max_{window}'] = profit.rolling(window=window, min_periods=1).max()
                data[f'profit_median_{window}'] = profit.rolling(window=window, min_periods=1).median()
                
                # Quantiles
                data[f'profit_q25_{window}'] = profit.rolling(window=window, min_periods=1).quantile(0.25)
                data[f'profit_q75_{window}'] = profit.rolling(window=window, min_periods=1).quantile(0.75)
                
                # Range and coefficient of variation
                data[f'profit_range_{window}'] = data[f'profit_max_{window}'] - data[f'profit_min_{window}']
                data[f'profit_cv_{window}'] = data[f'profit_std_{window}'] / (data[f'profit_mean_{window}'] + 0.001)
        
        return data


def integrate_profit_features_into_pipeline(data: pd.DataFrame, config: Optional[ProfitFeatureConfig] = None) -> pd.DataFrame:
    """
    Integrate profit-based feature engineering into the existing pipeline.
    
    This function should be called after triple barrier labeling to add
    profit-based features to the dataset.
    
    Args:
        data: DataFrame with 'potential_profit_pct' column from triple barrier labeling
        config: Configuration for profit feature engineering
        
    Returns:
        DataFrame with profit-based features added
    """
    if 'potential_profit_pct' not in data.columns:
        logging.warning("No 'potential_profit_pct' column found. Skipping profit feature engineering.")
        return data
    
    engineer = ProfitBasedFeatureEngineer(config)
    return engineer.create_all_profit_features(data)