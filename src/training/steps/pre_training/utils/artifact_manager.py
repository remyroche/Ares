    def get_artifact(self, step_name: str, key: str) -> Optional[Any]:
        """Enhanced artifact retrieval with caching and error handling."""
        canonical_step = canonical_step_name(step_name)
        candidate_steps = []
        if step_name:
            candidate_steps.append(step_name)
        if canonical_step not in candidate_steps:
            candidate_steps.append(canonical_step)
        candidate_steps.extend(
            alias for alias in _REVERSE_STEP_ALIASES.get(canonical_step, set())
            if alias not in candidate_steps
        )

        def _get_operation(**kwargs):
            entry = None
            resolved_step = None

            for candidate in candidate_steps:
                candidate_canonical = canonical_step_name(candidate)
                entry = self._artifacts.get(candidate_canonical, {}).get(key)
                if entry is not None:
                    resolved_step = candidate_canonical
                    break

                # Try to load from disk if not found in memory
                disk_artifacts = self._load_artifacts_from_disk(candidate_canonical)
                if key in disk_artifacts:
                    self._artifacts.setdefault(candidate_canonical, {})[key] = disk_artifacts[key]
                    entry = disk_artifacts[key]
                    resolved_step = candidate_canonical
                    break

            if entry is None or resolved_step is None:
                return None

            # Check cache first
            artifact_key = f"{resolved_step}:{key}"
            if self.config.enable_caching and artifact_key in self._cache:
                cache_entry = self._cache[artifact_key]
                cache_entry.last_accessed = datetime.utcnow()
                cache_entry.access_count += 1
                return cache_entry.data

            # Materialize from storage
            result = self._materialize(entry)

            # Update cache if enabled
            if result is not None and self.config.enable_caching:
                metadata = self._artifact_registry.get(artifact_key)
                if metadata:
                    self._update_cache_entry(artifact_key, result, metadata)

            return result

        return self._safe_operation(
            OperationType.LOAD,
            _get_operation,
            step_name=canonical_step,
            artifact_key=f"{canonical_step}:{key}"
        )

    def get_dataframe(self, step_name: str, key: str) -> Optional[pd.DataFrame]:
        value = self.get_artifact(step_name, key)
        if value is None:
            return None
        if isinstance(value, pd.DataFrame):
            return value
        if isinstance(value, pd.Series):
            return value.to_frame(name=value.name or key)
        return None

    def get_series(self, step_name: str, key: str) -> Optional[pd.Series]:
        value = self.get_artifact(step_name, key)
        if isinstance(value, pd.Series):
            return value
        if isinstance(value, pd.DataFrame) and key in value.columns:
            return value[key]
        return None

    def get_step_artifacts(self, step_name: str) -> Dict[str, Any]:
        """Return all artifacts stored for a step, resolving aliases and disk-backed entries."""
        canonical = canonical_step_name(step_name)
        steps_to_try = [canonical]
        steps_to_try.extend(
            alias for alias in _REVERSE_STEP_ALIASES.get(canonical, set())
            if alias not in steps_to_try
        )

        result: Dict[str, Any] = {}
        for candidate in steps_to_try:
            candidate_canonical = canonical_step_name(candidate)
            entries = self._artifacts.get(candidate_canonical)
            if not entries:
                entries = self._load_artifacts_from_disk(candidate_canonical)
                if entries:
                    existing = dict(self._artifacts.get(candidate_canonical, {}))
                    existing.update(entries)
                    self._artifacts[candidate_canonical] = existing

            if not entries:
                continue

            for key in entries.keys():
                if key in result:
                    continue
                value = self.get_artifact(candidate_canonical, key)
                if value is not None:
                    result[key] = value

        return result

    def store_enhanced(
        self,
        key: str,
        data: Any,
        metadata: Optional[Dict[str, Any]] = None,
        step_name: Optional[str] = None,
    ) -> bool:
        """Compatibility wrapper that infers the target step before saving."""
        inferred_step = step_name or (metadata or {}).get('step') or get_default_step_for_key(key) or "__shared__"
        canonical = canonical_step_name(inferred_step)

        metadata_to_store = dict(metadata or {})
        metadata_to_store.setdefault('step', canonical)

        try:
            self.save(
                step_name=canonical,
                artifacts={key: data},
                metadata=metadata_to_store
            )
            return True
        except Exception as exc:
            self._logger.error(f"Failed to store enhanced artifact {key}: {exc}", exc_info=True)
            return False

    def retrieve_enhanced(self, key: str, step_name: Optional[str] = None) -> Optional[Any]:
        """Compatibility wrapper that searches across known steps for a key."""
        candidates: List[str] = []
        if step_name:
            candidates.append(step_name)

        inferred_step = get_default_step_for_key(key)
        if inferred_step and inferred_step not in candidates:
            candidates.append(inferred_step)

        if "__shared__" not in candidates:
            candidates.append("__shared__")

        # Include loaded steps
        for registered_step in self._artifacts.keys():
            if registered_step not in candidates:
                candidates.append(registered_step)

        # Attempt retrieval
        for candidate in candidates:
            value = self.get_artifact(candidate, key)
            if value is not None:
                return value

        # Fallback to on-disk directories not yet loaded
        try:
            for directory in self.config.base_dir.iterdir():
                if not directory.is_dir():
                    continue
                candidate = canonical_step_name(directory.name)
                if candidate in candidates:
                    continue
                value = self.get_artifact(candidate, key)
                if value is not None:
                    return value
        except Exception as exc:  # pragma: no cover - best effort
            self._logger.debug(f"Enhanced retrieval disk scan failed: {exc}", exc_info=True)

        return None

    def get_metadata(self, step_name: str) -> Dict[str, Any]:
        canonical = canonical_step_name(step_name)
        base_meta = dict(self._metadata.get(canonical, {}))
        for alias in _REVERSE_STEP_ALIASES.get(canonical, set()):
            base_meta.update(self._metadata.get(alias, {}))
        return base_meta

    def list_steps(self) -> List[str]:
        return sorted({canonical_step_name(step) for step in self._artifacts.keys()})

    def _materialize(self, entry: StoredArtifact) -> Any:
        """Enhanced materialization with compression support."""
        # First check if the value is already a DataFrame or Series (regardless of kind)
        if isinstance(entry.value, pd.DataFrame):
            self._logger.debug(f"Returning DataFrame directly from entry: {entry.value.shape}")
            return entry.value
        if isinstance(entry.value, pd.Series):
            self._logger.debug(f"Returning Series directly from entry: {entry.value.shape}")
            return entry.value
        
        # Additional check for DataFrame-like objects
        if hasattr(entry.value, 'shape') and hasattr(entry.value, 'columns') and not isinstance(entry.value, (str, bytes, bytearray, memoryview)):
            self._logger.debug(f"Returning DataFrame-like object directly: {entry.value.shape}")
            return entry.value
            
        if entry.kind == "dataframe":
            return entry.value
        if entry.kind == "series":
            return entry.value

        # Handle compressed artifacts
        if entry.kind == "compressed_dataframe":
            try:
                # If already materialized, return directly
                if isinstance(entry.value, pd.DataFrame):
                    self._logger.debug(f"Returning existing DataFrame directly: {entry.value.shape}")
                    return entry.value
                if hasattr(entry.value, 'shape') and hasattr(entry.value, 'columns') and not isinstance(entry.value, (str, bytes, bytearray, memoryview)):
                    self._logger.debug(f"Detected DataFrame-like object, returning directly: {entry.value.shape}")
                    return entry.value

                # Only decompress if value is bytes-like
                if isinstance(entry.value, (bytes, bytearray, memoryview)):
                    compression_type = CompressionType(entry.metadata.get('compression_type', 'none'))
                    self._logger.debug(f"Decompressing dataframe with compression type: {compression_type}")
                    decompressed_data = self._compressor.decompress_data(entry.value, compression_type)
                    return pickle.loads(decompressed_data)
                else:
                    self._logger.debug(f"Returning non-bytes dataframe object as-is: {type(entry.value)}")
                    return entry.value
            except Exception as e:
                self._logger.error(f"Failed to decompress dataframe: {e}")
                self._logger.debug(f"Entry value type: {type(entry.value)}")
                return None

        if entry.kind == "compressed_series":
            try:
                # If already materialized, return directly
                if isinstance(entry.value, pd.Series):
                    self._logger.debug(f"Returning existing Series directly: {entry.value.shape}")
                    return entry.value
                if hasattr(entry.value, 'shape') and hasattr(entry.value, 'index') and not isinstance(entry.value, (str, bytes, bytearray, memoryview)):
                    self._logger.debug(f"Detected Series-like object, returning directly: {entry.value.shape}")
                    return entry.value

                # Only decompress if value is bytes-like
                if isinstance(entry.value, (bytes, bytearray, memoryview)):
                    compression_type = CompressionType(entry.metadata.get('compression_type', 'none'))
                    self._logger.debug(f"Decompressing series with compression type: {compression_type}")
                    decompressed_data = self._compressor.decompress_data(entry.value, compression_type)
                    return pickle.loads(decompressed_data)
                else:
                    self._logger.debug(f"Returning non-bytes series object as-is: {type(entry.value)}")
                    return entry.value
            except Exception as e:
                self._logger.error(f"Failed to decompress series: {e}")
                self._logger.debug(f"Entry value type: {type(entry.value)}")
                return None

        if entry.kind == "compressed_object":
            try:
                # If already materialized, return directly
                if isinstance(entry.value, pd.DataFrame):
                    self._logger.debug(f"Returning existing DataFrame directly: {entry.value.shape}")
                    return entry.value
                if isinstance(entry.value, pd.Series):
                    self._logger.debug(f"Returning existing Series directly: {entry.value.shape}")
                    return entry.value

                # DataFrame-like or Series-like objects (stored uncompressed)
                if hasattr(entry.value, 'shape') and not isinstance(entry.value, (str, bytes, bytearray, memoryview)):
                    if hasattr(entry.value, 'columns'):
                        self._logger.debug(f"Detected DataFrame-like object, returning directly: {entry.value.shape}")
                    elif hasattr(entry.value, 'index'):
                        self._logger.debug(f"Detected Series-like object, returning directly: {entry.value.shape}")
                    return entry.value

                # Only attempt decompression if value is bytes-like
                if isinstance(entry.value, (bytes, bytearray, memoryview)):
                    compression_type = CompressionType(entry.metadata.get('compression_type', 'none'))
                    self._logger.debug(f"Decompressing object with compression type: {compression_type}")
                    decompressed_data = self._compressor.decompress_data(entry.value, compression_type)
                    return pickle.loads(decompressed_data)

                # Fallback: return as-is
                self._logger.debug(f"Returning non-bytes object as-is: {type(entry.value)}")
                return entry.value

            except Exception as e:
                self._logger.error(f"Failed to decompress object: {e}")
                self._logger.debug(f"Entry value type: {type(entry.value)}")
                return None

        if entry.kind == "dataframe_pointer":
            if entry.path and entry.path.exists():
                df = pd.read_parquet(entry.path)
                if self.config.cache_materialized:
                    entry.value = df
                    entry.kind = "dataframe"
                return df
            self._logger.warning("Missing persisted dataframe at %s", entry.path)
            return None
        if entry.kind == "series_pointer":
            if entry.path and entry.path.exists():
                df = pd.read_parquet(entry.path)
                col = entry.metadata.get('column')
                series = df[col] if col and col in df.columns else df.iloc[:, 0]
                if self.config.cache_materialized:
                    entry.value = series
                    entry.kind = "series"
                return series
            self._logger.warning("Missing persisted series at %s", entry.path)
            return None
        return entry.value

